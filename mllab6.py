class Human_KNN:
    """Basic iterative implementation from Lab 5 to serve as the baseline."""
    def __init__(self, n_neighbors=3):
        self.k = n_neighbors
    def fit(self, X, y):
        self.X_train, self.y_train = np.array(X), np.array(y)
    def predict(self, X_test):
        preds = []
        for test_pt in np.array(X_test):
            dists = [np.sqrt(np.sum((test_pt - train_pt)**2)) for train_pt in self.X_train]
            # Slower full sorting
            k_indices = np.argsort(dists)[:self.k]
            k_labels = [self.y_train[i] for i in k_indices]
            preds.append(Counter(k_labels).most_common(1)[0][0])
        return np.array(preds)


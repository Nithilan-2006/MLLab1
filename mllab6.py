class AI_Optimized_KNN:
    """
    Highly optimized kNN using NumPy broadcasting and np.argpartition for O(N) sorting.
    GenAI Prompt: "Generate a highly optimized, fully vectorized kNN classifier in Python using NumPy."
    """
    def __init__(self, n_neighbors=3, metric='euclidean', weighted=False):
        self.k = n_neighbors
        self.metric = metric
        self.weighted = weighted
        self.X_train = None
        self.y_train = None

    def fit(self, X, y):
        self.X_train = np.array(X)
        self.y_train = np.array(y)
        return self

    def _compute_distances(self, X_test):
        # GenAI Optimization: Vectorized Euclidean distance using (a-b)^2 = a^2 + b^2 - 2ab
        if self.metric == 'euclidean':
            test_sq = np.sum(X_test**2, axis=1, keepdims=True)
            train_sq = np.sum(self.X_train**2, axis=1)
            cross_term = np.dot(X_test, self.X_train.T)
            dists = np.sqrt(np.maximum(test_sq + train_sq - 2 * cross_term, 0))
            return dists
        else:
            # Fallback for manhattan
            return np.sum(np.abs(X_test[:, np.newaxis] - self.X_train), axis=2)

    def predict(self, X_test):
        X_test = np.array(X_test)
        dists = self._compute_distances(X_test)

        # GenAI Optimization: Use argpartition instead of full sort (O(N) instead of O(N log N))
        knn_indices = np.argpartition(dists, self.k, axis=1)[:, :self.k]
        predictions = []

        for i, neighbor_idx in enumerate(knn_indices):
            neighbor_dists = dists[i, neighbor_idx]
            neighbor_labels = self.y_train[neighbor_idx]

            if not self.weighted:
                # Fast majority voting
                most_common = Counter(neighbor_labels).most_common(1)[0][0]
                predictions.append(most_common)
            else:
                # Distance-weighted voting
                weights = 1.0 / (neighbor_dists + 1e-8)
                weighted_votes = {}
                for label, w in zip(neighbor_labels, weights):
                    weighted_votes[label] = weighted_votes.get(label, 0) + w
                best_label = max(weighted_votes, key=weighted_votes.get)
                predictions.append(best_label)

        return np.array(predictions)

